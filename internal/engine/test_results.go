package engine

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
	"warlink/internal/deps"
)

type ConfigScore struct {
	ConfigName string
	OkCount    int
	ErrCount   int
	PingAvgMs  int
}

type ZapretTestSummary struct {
	ReportFile string
	Scores     []ConfigScore
	BestConfig string
}

var reConfigHeader = regexp.MustCompile(`(?i)^Config:\s*([^\r\n]+?)(?:\s*\(Type:|\s*$)`)
var rePing = regexp.MustCompile(`(?i)Ping:\s*(\d+)\s*ms`)
var reBestStrategy = regexp.MustCompile(`(?i)Best strategy:\s*([^\r\n]+)`)

// FindLatestZapretReport scans warlink_core/zapret/utils/test results/ for test_results_*.txt
func FindLatestZapretReport() (string, error) {
	resultsDir := filepath.Join(deps.GetZapretDir(), "utils", "test results")
	entries, err := os.ReadDir(resultsDir)
	if err != nil {
		return "", err
	}

	var latestPath string
	var latestMod time.Time

	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if strings.HasPrefix(strings.ToLower(name), "test_results_") && strings.HasSuffix(strings.ToLower(name), ".txt") {
			fullPath := filepath.Join(resultsDir, name)
			info, err := entry.Info()
			if err == nil {
				if latestPath == "" || info.ModTime().After(latestMod) {
					latestPath = fullPath
					latestMod = info.ModTime()
				}
			}
		}
	}

	if latestPath == "" {
		return "", fmt.Errorf("отчеты тестирования не найдены")
	}

	return latestPath, nil
}

// ParseZapretReport parses an official test_results_*.txt file generated by test zapret.ps1
func ParseZapretReport(reportPath string) (*ZapretTestSummary, error) {
	file, err := os.Open(reportPath)
	if err != nil {
		return nil, err
	}
	defer file.Close()

	scanner := bufio.NewScanner(file)
	var currentScore *ConfigScore
	var scores []ConfigScore
	var currentPings []int
	var explicitBest string

	for scanner.Scan() {
		line := scanner.Text()
		trimmed := strings.TrimSpace(line)

		if strings.HasPrefix(trimmed, "Best strategy:") {
			m := reBestStrategy.FindStringSubmatch(trimmed)
			if len(m) > 1 {
				explicitBest = strings.TrimSpace(m[1])
			}
			continue
		}

		if strings.HasPrefix(trimmed, "Config:") {
			if currentScore != nil {
				if len(currentPings) > 0 {
					sum := 0
					for _, p := range currentPings {
						sum += p
					}
					currentScore.PingAvgMs = sum / len(currentPings)
				}
				scores = append(scores, *currentScore)
			}

			matches := reConfigHeader.FindStringSubmatch(trimmed)
			cName := trimmed
			if len(matches) > 1 {
				cName = strings.TrimSpace(matches[1])
			}
			currentScore = &ConfigScore{
				ConfigName: cName,
			}
			currentPings = nil
			continue
		}

		if currentScore != nil {
			// Count OK and ERROR
			okCount := strings.Count(line, "OK")
			errCount := strings.Count(line, "ERROR") + strings.Count(line, "FAIL")
			currentScore.OkCount += okCount
			currentScore.ErrCount += errCount

			// Ping
			pMatches := rePing.FindStringSubmatch(line)
			if len(pMatches) > 1 {
				var p int
				_, _ = fmt.Sscanf(pMatches[1], "%d", &p)
				if p > 0 {
					currentPings = append(currentPings, p)
				}
			}
		}
	}

	if currentScore != nil {
		if len(currentPings) > 0 {
			sum := 0
			for _, p := range currentPings {
				sum += p
			}
			currentScore.PingAvgMs = sum / len(currentPings)
		}
		scores = append(scores, *currentScore)
	}

	if len(scores) == 0 {
		return nil, fmt.Errorf("в файле отчета %s нет данных о конфигурациях", reportPath)
	}

	// Sort: Most OK first, then fewest ERR, then lowest ping
	sort.SliceStable(scores, func(i, j int) bool {
		if scores[i].OkCount != scores[j].OkCount {
			return scores[i].OkCount > scores[j].OkCount
		}
		if scores[i].ErrCount != scores[j].ErrCount {
			return scores[i].ErrCount < scores[j].ErrCount
		}
		return scores[i].PingAvgMs < scores[j].PingAvgMs
	})

	best := scores[0].ConfigName
	if explicitBest != "" {
		best = explicitBest
	}
	// Ensure .bat extension
	if !strings.HasSuffix(strings.ToLower(best), ".bat") {
		best += ".bat"
	}

	return &ZapretTestSummary{
		ReportFile: filepath.Base(reportPath),
		Scores:     scores,
		BestConfig: best,
	}, nil
}
